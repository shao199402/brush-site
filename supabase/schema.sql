-- 笔刷商品目录 · 订单库（Supabase / PostgreSQL）
--
-- 用法：Supabase 控制台 → SQL Editor → 新建查询 → 整段粘贴 → Run
--
-- 设计要点：
--   1. 前端只有 anon key（公开的），**不允许直接 INSERT**，否则谁都能刷单。
--      下单统一走 submit_order() 这个 RPC：函数内部做频率限制，
--      并且只接受白名单字段（多余字段忽略）。
--   2. 后台（固定人员）用邮箱密码登录 Supabase Auth，
--      只有 app_settings.admin_email 里那个邮箱能读订单。
--   3. 商品明细存 jsonb 而不是拆表，保证「一次请求写完一张订单」的原子性。
-- ══════════════════════════════════════════════════════════════════

-- ── 1. 订单表 ────────────────────────────────────────────────
create table if not exists public.orders (
  id                bigint generated by default as identity primary key,
  order_no          text not null unique,
  created_at        timestamptz not null default now(),
  status            text not null default 'pending'
                    check (status in ('pending','paid','shipped','done','cancelled')),
  customer_name     text not null,
  customer_phone    text not null,
  customer_address  text not null,
  customer_note     text,
  items             jsonb not null default '[]'::jsonb,   -- [{brand,title,amount,currency,qty}]
  subtotals         jsonb not null default '{}'::jsonb,   -- {JPY: 31130, CNY: 45}
  order_text        text,                                  -- 人可读的完整订单文本
  source_page       text,                                  -- 从哪个品牌页下的单
  handled_note      text                                   -- 客服内部备注
);

create index if not exists orders_created_at_idx on public.orders (created_at desc);
create index if not exists orders_status_idx     on public.orders (status);
create index if not exists orders_phone_idx      on public.orders (customer_phone);

-- ── 2. 配置表（存管理员邮箱）────────────────────────────────
create table if not exists public.app_settings (
  key   text primary key,
  value text not null
);

-- ⚠ 把下面的邮箱改成「固定人员」登录后台用的邮箱，必须和 Supabase Auth 里创建的用户一致
insert into public.app_settings (key, value)
values ('admin_email', 'admin@example.com')
on conflict (key) do update set value = excluded.value;

-- ── 3. 下单 RPC（前端唯一能调用的写入口）────────────────────
create or replace function public.submit_order(payload jsonb)
returns jsonb
language plpgsql
security definer            -- 以函数所有者身份执行，绕过 RLS 写表
set search_path = public
as $$
declare
  v_phone    text := nullif(trim(payload->>'customer_phone'), '');
  v_name     text := nullif(trim(payload->>'customer_name'), '');
  v_address  text := nullif(trim(payload->>'customer_address'), '');
  v_order_no text := nullif(trim(payload->>'order_no'), '');
  v_recent   int;
begin
  -- 必填校验
  if v_phone is null or v_name is null or v_address is null or v_order_no is null then
    return jsonb_build_object('ok', false, 'error', '缺少必填字段');
  end if;
  if length(v_address) < 5 or length(v_phone) < 5 then
    return jsonb_build_object('ok', false, 'error', '信息不完整');
  end if;

  -- 频率限制：同一手机号 10 分钟内最多 5 单（防误点/防刷）
  select count(*) into v_recent
    from public.orders
   where customer_phone = v_phone
     and created_at > now() - interval '10 minutes';
  if v_recent >= 5 then
    return jsonb_build_object('ok', false, 'error', '提交过于频繁，请稍后再试或直接联系客服');
  end if;

  insert into public.orders (
    order_no, customer_name, customer_phone, customer_address, customer_note,
    items, subtotals, order_text, source_page
  ) values (
    v_order_no, v_name, v_phone, v_address, nullif(trim(payload->>'customer_note'), ''),
    coalesce(payload->'items', '[]'::jsonb),
    coalesce(payload->'subtotals', '{}'::jsonb),
    nullif(payload->>'order_text', ''),
    nullif(payload->>'source_page', '')
  );

  return jsonb_build_object('ok', true, 'order_no', v_order_no);
exception
  when unique_violation then
    return jsonb_build_object('ok', false, 'error', '订单号重复，请重试');
end;
$$;

-- 只给匿名用户「执行这个函数」的权限，不给表的写权限
revoke all on function public.submit_order(jsonb) from public;
grant execute on function public.submit_order(jsonb) to anon, authenticated;

-- ── 4. 行级安全策略 ─────────────────────────────────────────
alter table public.orders       enable row level security;
alter table public.app_settings enable row level security;

-- 订单表：**不给 anon 任何策略** → 匿名既读不到也写不进（写入只走 RPC）
-- 管理员（邮箱与 app_settings.admin_email 一致的登录用户）可读可改
drop policy if exists "admin read orders"   on public.orders;
drop policy if exists "admin update orders" on public.orders;

create policy "admin read orders" on public.orders
  for select to authenticated
  using (
    (auth.jwt() ->> 'email') = (select value from public.app_settings where key = 'admin_email')
  );

create policy "admin update orders" on public.orders
  for update to authenticated
  using (
    (auth.jwt() ->> 'email') = (select value from public.app_settings where key = 'admin_email')
  )
  with check (
    (auth.jwt() ->> 'email') = (select value from public.app_settings where key = 'admin_email')
  );

-- 配置表：登录用户可读（策略还要读这张表），匿名不可读
drop policy if exists "settings readable by authenticated" on public.app_settings;
create policy "settings readable by authenticated" on public.app_settings
  for select to authenticated using (true);

